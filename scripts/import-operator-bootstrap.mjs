#!/usr/bin/env node
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import readline from 'readline';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

function argValue(name) {
  const prefix = `${name}=`;
  const match = process.argv.find((arg) => arg.startsWith(prefix));
  if (match) return match.slice(prefix.length);
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : '';
}

function positionalBundlePath() {
  return process.argv.slice(2).find((arg) => !arg.startsWith('--')) || '';
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function hiddenQuestion(promptText) {
  if (process.env.BNA_BOOTSTRAP_PASSPHRASE) return Promise.resolve(process.env.BNA_BOOTSTRAP_PASSPHRASE);
  if (!process.stdin.isTTY) {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    return new Promise((resolve) => rl.question(promptText, (answer) => {
      rl.close();
      resolve(answer);
    }));
  }

  return new Promise((resolve, reject) => {
    const stdin = process.stdin;
    const wasRaw = stdin.isRaw;
    let value = '';
    process.stdout.write(promptText);
    readline.emitKeypressEvents(stdin);
    stdin.setRawMode(true);
    stdin.resume();

    function cleanup() {
      stdin.removeListener('keypress', onKeypress);
      stdin.setRawMode(Boolean(wasRaw));
      process.stdout.write('\n');
    }

    function onKeypress(str, key = {}) {
      if (key.ctrl && key.name === 'c') {
        cleanup();
        reject(new Error('Cancelled'));
        return;
      }
      if (key.name === 'return' || key.name === 'enter') {
        cleanup();
        resolve(value);
        return;
      }
      if (key.name === 'backspace') {
        value = value.slice(0, -1);
        return;
      }
      if (str && !key.ctrl && !key.meta) value += str;
    }

    stdin.on('keypress', onKeypress);
  });
}

function decryptPackage(bundle, passphrase) {
  const enc = bundle?.body?.encryption;
  if (!enc || enc.algorithm !== 'aes-256-gcm' || enc.kdf !== 'scrypt') {
    throw new Error('Unsupported encrypted bootstrap package.');
  }
  const key = crypto.scryptSync(String(passphrase || ''), Buffer.from(enc.salt, 'base64'), 32);
  const decipher = crypto.createDecipheriv('aes-256-gcm', key, Buffer.from(enc.iv, 'base64'));
  decipher.setAuthTag(Buffer.from(enc.auth_tag, 'base64'));
  const plaintext = Buffer.concat([
    decipher.update(Buffer.from(enc.ciphertext, 'base64')),
    decipher.final(),
  ]);
  return JSON.parse(plaintext.toString('utf8'));
}

function dotenvValue(value) {
  const raw = String(value ?? '');
  if (/^[A-Za-z0-9_@%+=:,./-]*$/.test(raw)) return raw;
  return JSON.stringify(raw);
}

function writeEnvFile(env, targetPath, { force = false } = {}) {
  const keys = Object.keys(env || {}).filter((key) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(key));
  const body = [
    '# Generated by scripts/import-operator-bootstrap.mjs',
    '# Do not commit this file.',
    ...keys.map((key) => `${key}=${dotenvValue(env[key])}`),
    '',
  ].join('\n');

  let finalPath = targetPath;
  if (fs.existsSync(finalPath) && !force) {
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    finalPath = path.join(path.dirname(targetPath), `.env.local.from-bootstrap-${stamp}`);
  }
  fs.writeFileSync(finalPath, body, { encoding: 'utf8', flag: force ? 'w' : 'wx' });
  return { path: finalPath, keys: keys.length };
}

async function main() {
  const bundlePath = path.resolve(argValue('--bundle') || positionalBundlePath());
  if (!bundlePath || !fs.existsSync(bundlePath)) {
    console.error('Usage: node scripts/import-operator-bootstrap.mjs path\\to\\bna-operator-bootstrap.json [--force]');
    process.exit(1);
  }

  const force = process.argv.includes('--force');
  const bundle = readJson(bundlePath);
  if (bundle.package_type !== 'bna_operator_bootstrap') {
    throw new Error('This is not a BNA operator bootstrap package.');
  }

  const expired = bundle.expires_at && Date.now() > new Date(bundle.expires_at).getTime();
  if (expired && !process.argv.includes('--allow-expired')) {
    throw new Error('This bootstrap package is expired. Generate a fresh package from Operations.');
  }

  const payload = bundle.encrypted
    ? decryptPackage(bundle, await hiddenQuestion('Bootstrap passphrase: '))
    : { env: bundle.body?.env_template || {} };

  const env = payload.env || {};
  if (!Object.keys(env).length) throw new Error('The bootstrap package did not contain an env payload.');

  fs.mkdirSync(path.join(repoRoot, '.runtime'), { recursive: true });
  const result = writeEnvFile(env, path.join(repoRoot, '.env.local'), { force });
  console.log('BNA operator bootstrap imported.');
  console.log(`Env keys written: ${result.keys}`);
  console.log(`Target: ${path.relative(repoRoot, result.path)}`);
  console.log('No secret values were printed.');
}

main().catch((error) => {
  console.error(error.message || String(error));
  process.exit(1);
});
