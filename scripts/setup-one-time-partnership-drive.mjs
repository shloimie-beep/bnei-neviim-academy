function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function loadClient() {
  const parsed = readJson(clientPath);
  const client = parsed.web || parsed.installed;
  if (!client?.client_id || !client?.client_secret) {
    throw new Error(`Invalid Google OAuth client JSON at ${clientPath}`);
  }
  return {
    clientId: client.client_id,
    clientSecret: client.client_secret,
    redirectUri: process.env.GOOGLE_REDIRECT_URI || client.redirect_uris?.[0],
  };
}

function loadRefreshToken() {
  if (process.env.GOOGLE_REFRESH_TOKEN) return process.env.GOOGLE_REFRESH_TOKEN;
  if (fs.existsSync(tokenPath)) return fs.readFileSync(tokenPath, 'utf8').trim();
  throw new Error(`Missing Google refresh token at ${tokenPath}`);
}

function authWithRefreshToken() {
  const client = loadClient();
  const auth = new google.auth.OAuth2(client.clientId, client.clientSecret, client.redirectUri);
  auth.setCredentials({ refresh_token: loadRefreshToken() });
  return auth;
}

function driveLiteral(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

async function findFolder(drive, name, parentId = 'root') {
  const result = await drive.files.list({
    q: [
      "mimeType='application/vnd.google-apps.folder'",
      'trashed=false',
      `name='${driveLiteral(name)}'`,
      `'${driveLiteral(parentId)}' in parents`,
    ].join(' and '),
    fields: 'files(id,name,webViewLink,parents)',
    pageSize: 10,
    supportsAllDrives: true,
    includeItemsFromAllDrives: true,
  });
  return result.data.files?.[0] || null;
}

async function ensureFolder(drive, name, parentId = 'root') {
  const existing = await findFolder(drive, name, parentId);
  if (existing) return { ...existing, created: false };
  const created = await drive.files.create({
    requestBody: {
      name,
      mimeType: 'application/vnd.google-apps.folder',
      parents: parentId === 'root' ? undefined : [parentId],
    },
    fields: 'id,name,webViewLink,parents',
    supportsAllDrives: true,
  });
  return { ...created.data, created: true };
}

async function ensureFolderWithAliases(drive, folder, parentId = 'root') {
  const names = [folder.name].concat(folder.previousNames || []);
  for (const name of names) {
    const existing = await findFolder(drive, name, parentId);
    if (existing) {
      return {
        ...existing,
        name: folder.name,
        actualName: existing.name,
        created: false,
        reused: true,
        reusedSemanticAlias: existing.name !== folder.name,
      };
    }
  }
  const created = await ensureFolder(drive, folder.name, parentId);
  return {
    ...created,
    actualName: created.name,
    reused: false,
    reusedSemanticAlias: false,
  };
}

