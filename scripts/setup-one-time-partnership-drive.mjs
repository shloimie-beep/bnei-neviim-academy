function markdownReport(context) {
  const lines = [
    `# One Time Partnership Drive Map - ${context.generatedAt}`,
    '',
    `Root: ${context.root.name}`,
    `Project folder: [${context.projectFolder.name}](${context.projectFolder.webViewLink})`,
    '',
    '## Proposal',
    '',
    context.proposalCopy?.file
      ? `- Project copy: [${context.proposalCopy.file.name}](${context.proposalCopy.file.webViewLink})`
      : '- Proposal file was not found by name search.',
    context.proposalCopy?.sourceFile?.webViewLink
      ? `- Original upload preserved: [${context.proposalCopy.sourceFile.name}](${context.proposalCopy.sourceFile.webViewLink})`
      : '- Original upload link was not available.',
    context.proposalCopy?.copied
      ? `- Copied into: ${context.subfoldersByKey.startHere.name}`
      : `- Copy status: ${context.proposalCopy?.reason || 'not copied'}`,
    context.archivedProposal?.file?.webViewLink
      ? `- Historical June 9 draft: [${context.archivedProposal.file.name}](${context.archivedProposal.file.webViewLink}) (${context.archivedProposal.reason})`
      : `- Historical June 9 draft archive status: ${context.archivedProposal?.reason || 'not checked'}`,
    ...(context.archivedSupersededProposalCopies?.length
      ? context.archivedSupersededProposalCopies.map((archived) => (
        `- Superseded Start Here copy archived: [${archived.file.name}](${archived.file.webViewLink})`
      ))
      : ['- Superseded Start Here copies archived: none found']),
    '',
    '## Subfolders',
    '',
  ];
  for (const folder of context.subfolders) {
    lines.push(`- [${folder.name}](${folder.webViewLink}) - ${folder.purpose}`);
  }
  lines.push('', '## Content And Social Intake Lanes', '');
  for (const folder of context.contentMediaIntakeFolders || []) {
    lines.push(`- [${folder.name}](${folder.webViewLink}) - ${folder.driveStage}. ${folder.purpose}`);
  }
  lines.push('', '## Starter Docs', '');
  for (const doc of context.docs) {
    lines.push(`- [${doc.name}](${doc.webViewLink})`);
  }
  return `${lines.join('\n')}\n`;
}

async function main() {
  const auth = authWithRefreshToken();
  const drive = google.drive({ version: 'v3', auth });
  const docs = google.docs({ version: 'v1', auth });
  const generatedAt = new Date().toISOString();

  const root = { id: 'root', name: 'Google Drive My Drive root', webViewLink: 'https://drive.google.com/drive/my-drive' };
  const projectFolder = await ensureFolder(drive, PROJECT_FOLDER_NAME, 'root');
  const subfolders = [];
  const subfoldersByKey = {};
  for (const folder of SUBFOLDERS) {
    const ensured = await ensureFolder(drive, folder.name, projectFolder.id);
    const value = { ...folder, ...ensured };
    subfolders.push(value);
    subfoldersByKey[folder.key] = value;
  }
  const contentMediaIntakeFolders = [];
  for (const folder of CONTENT_MEDIA_INTAKE_FOLDERS) {
    const ensured = await ensureFolderWithAliases(drive, folder, subfoldersByKey.contentMedia.id);
    contentMediaIntakeFolders.push({ ...folder, ...ensured });
  }
  const historicalDraftsFolder = await ensureFolder(drive, 'Historical Drafts', subfoldersByKey.done.id);

  const proposal = await findLatestProposal(drive, [
    projectFolder.id,
    subfoldersByKey.startHere.id,
    historicalDraftsFolder.id,
  ]);
  const proposalCopy = proposal
    ? await copyFileIntoFolder(drive, proposal, subfoldersByKey.startHere.id)
    : { copied: false, reason: 'proposal-not-found' };
  const archivedProposal = await archiveOldProposalCopy(
    drive,
    subfoldersByKey.startHere.id,
    historicalDraftsFolder.id,
    proposalCopy?.file?.id || proposal?.id || null
  );
  const archivedSupersededProposalCopies = await archiveSupersededStartHereProposalCopies(
    drive,
    subfoldersByKey.startHere.id,
    historicalDraftsFolder.id,
    proposalCopy?.file?.id || proposal?.id || null
  );

  const context = {
    generatedAt,
    root,
    projectFolder,
    subfolders,
    subfoldersByKey,
    proposal,
    proposalCopy,
    historicalDraftsFolder,
    archivedProposal,
    archivedSupersededProposalCopies,
    contentMediaIntakeFolders,
    docs: [],
  };

  const docDefinitions = [
    ['00 One Time Partnership Project Map', projectMapText(context)],
    ['01 Task Map - Codex Claude Shloimie Rabbi Elie', taskMapText(context)],
    ['02 Drive Folder Rules', folderRulesText(context)],
  ];
  for (const [name, text] of docDefinitions) {
    const doc = await ensureDoc(drive, name, subfoldersByKey.startHere.id);
    await replaceDocText(docs, doc.id, text);
    context.docs.push(doc);
  }

  fs.mkdirSync(reportDir, { recursive: true });
  const jsonPath = path.join(reportDir, 'partnership-drive-map.json');
  const markdownPath = path.join(reportDir, 'partnership-drive-map.md');
  const driveSocialMap = driveSocialIngestionMap(context);
  const driveSocialJsonPath = path.join(reportDir, 'drive-social-ingestion-map.json');
  const driveSocialMarkdownPath = path.join(reportDir, 'drive-social-ingestion-map.md');
  fs.writeFileSync(jsonPath, `${JSON.stringify({
    generatedAt,
    root,
    projectFolder,
    subfolders,
    contentMediaIntakeFolders,
    proposal: context.proposal || null,
    proposalCopy,
    historicalDraftsFolder,
    archivedProposal,
    archivedSupersededProposalCopies,
    docs: context.docs,
  }, null, 2)}\n`);
  fs.writeFileSync(markdownPath, markdownReport(context));
  fs.writeFileSync(driveSocialJsonPath, `${JSON.stringify(driveSocialMap, null, 2)}\n`);
  fs.writeFileSync(driveSocialMarkdownPath, driveSocialIngestionMarkdown(driveSocialMap));

  console.log(`One Time partnership Drive folder confirmed: ${projectFolder.webViewLink}`);
  console.log(`One Time Drive/social ingestion lanes confirmed: ${contentMediaIntakeFolders.length}`);
  if (context.proposalCopy?.file?.webViewLink) {
    console.log(`Proposal copy filed: ${context.proposalCopy.file.webViewLink}`);
  } else {
    console.log('Proposal file was not found by name search.');
  }
  console.log(`Historical draft archive status: ${context.archivedProposal?.reason || 'not checked'}`);
  if (context.archivedSupersededProposalCopies?.length) {
    console.log(`Archived superseded Start Here copies: ${context.archivedSupersededProposalCopies.length}`);
  }
  console.log(`Report written: ${path.relative(repoRoot, markdownPath)}`);
  console.log(`Drive/social map written: ${path.relative(repoRoot, driveSocialMarkdownPath)}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack || error.message : String(error));
  process.exitCode = 1;
});
