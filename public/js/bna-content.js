  let publishedWebsitePosts = [];
  let publishedWebsitePostsPromise = null;

  function normalizePublishedPost(post) {
    if (!post || !post.slug || !post.title) return null;
    return {
      lang: post.lang || "en",
      slug: post.slug,
      category: post.category || "Torah Learning",
      title: post.title,
      metaTitle: post.metaTitle || `${post.title} | Bnei Neviim Academy`,
      metaDescription: post.metaDescription || post.excerpt || site.description,
      keywords: Array.isArray(post.keywords) ? post.keywords : keywords.en,
      image: post.image || "/images/learning-moments/forest-learning-01-web.jpg",
      excerpt: post.excerpt || post.metaDescription || "",
      body: Array.isArray(post.body) ? post.body : [],
      cta:
        post.cta ||
        "Contact Bnei Neviim Academy to discuss whether this Torah learning environment is the right fit for your son.",
      publishedAt: post.publishedAt || "",
      generated: true,
    };
  }

  function allPosts() {
    const byKey = new Map();
    [...publishedWebsitePosts, ...blogPosts].forEach((post) => {
      const key = `${post.lang}:${post.slug}`;
      if (!byKey.has(key)) byKey.set(key, post);
    });
    return [...byKey.values()];
  }

  async function loadPublishedPosts() {
    if (publishedWebsitePostsPromise) return publishedWebsitePostsPromise;
    publishedWebsitePostsPromise = fetch("/data/website-blog-posts.json", { cache: "no-store" })
      .then((response) => (response.ok ? response.json() : { posts: [] }))
      .then((data) => {
        publishedWebsitePosts = Array.isArray(data.posts)
          ? data.posts.map(normalizePublishedPost).filter(Boolean)
          : [];
        return publishedWebsitePosts;
      })
      .catch(() => {
        publishedWebsitePosts = [];
        return publishedWebsitePosts;
      });
    return publishedWebsitePostsPromise;
  }

  function getPosts(lang) {
    return allPosts()
      .filter((post) => post.lang === lang)
      .sort((a, b) => {
        if (a.generated && !b.generated) return -1;
        if (!a.generated && b.generated) return 1;
        return String(b.publishedAt || "").localeCompare(String(a.publishedAt || ""));
      });
  }

  function getPost(lang, slug) {
    return allPosts().find((post) => post.lang === lang && post.slug === slug);
  }

  function relatedPosts(post, limit = 3) {
    return getPosts(post.lang)
      .filter((candidate) => candidate.slug !== post.slug)
      .sort((a, b) => {
        if (a.category === post.category && b.category !== post.category) return -1;
        if (a.category !== post.category && b.category === post.category) return 1;
        return a.title.localeCompare(b.title);
      })
      .slice(0, limit);
  }

  window.BNAContent = {
    site,
    categories,
    keywords,
    blogPosts,
    loadPublishedPosts,
    faqs,
    getPosts,
    getPost,
    relatedPosts,
  };
